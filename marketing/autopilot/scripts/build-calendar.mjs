#!/usr/bin/env node
// Regenerate the human review calendar FROM posts.json — the JSON is the source of truth.
//   node marketing/autopilot/scripts/build-calendar.mjs <out.md> <week-dir>...
// Keeps the two from drifting: never hand-edit the generated sections.
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve, basename } from 'node:path';

const [out, ...dirs] = process.argv.slice(2);
if (!out || !dirs.length) { console.error('usage: build-calendar.mjs <out.md> <week-dir>...'); process.exit(1); }

const cfg = JSON.parse(readFileSync(new URL('../channels.json', import.meta.url)));
const TZ = cfg.timezone;
const LABEL = {
  'junaid-x': 'X — @JustJunaidHere (voice-junaid, founder)',
  'sendemall-x': 'X — @SendEmAll (voice-brand, category POV)',
  'sadiya-li': 'LinkedIn — Sadiya Junaid (voice-sadiya)',
  'sadiya-x': 'X — Sadiya (voice-sadiya)',
  'kamran-li': 'LinkedIn — Kamran (voice-kamran, infrastructure)',
  'naved-li': 'LinkedIn — Naved (voice-naved, GTM operator)',
  'sendemall-li': 'LinkedIn — SendEmAll company page (voice-brand)',
};
const fmt = (iso, opts) => new Intl.DateTimeFormat('en-US', { timeZone: TZ, ...opts }).format(new Date(iso));
const slot = (iso) => `${fmt(iso, { weekday: 'short', month: 'short', day: 'numeric' })} | ${fmt(iso, { hour: 'numeric', minute: '2-digit', hour12: true })} ET`;

let md = `# Content Calendar — Relaunch Weeks\n\n`;
md += `<!-- GENERATED by scripts/build-calendar.mjs from posts.json — do not hand-edit post text.\n`;
md += `     Edit the JSON, then re-run the script. -->\n\n`;
md += `**Status: PROPOSED — nothing publishes until approved.** Flip \`"proposed"\` → \`"approved"\` in the\n`;
md += `week's \`posts.json\`, then \`node marketing/autopilot/scripts/publish.mjs <week-dir>\`.\n\n`;
md += `- 🔶 = personal story needing Sadiya's confirmation before approval (\`needsConfirmation\`).\n`;
md += `- ⛔ = SendEmAll LinkedIn page; cannot be scheduled until the LinkedIn app is approved for the\n`;
md += `  Community Management API (the Page provider needs org scopes our app is not authorized for).\n`;

for (const dir of dirs) {
  const posts = JSON.parse(readFileSync(resolve(dir, 'posts.json'), 'utf8'))
    .sort((a, b) => a.date.localeCompare(b.date));
  const days = posts.map((p) => fmt(p.date, { month: 'short', day: 'numeric' }));
  md += `\n---\n\n# ═══ ${basename(dir)} — ${days[0]} to ${days.at(-1)} ═══\n`;
  md += `\n_${posts.length} posts · ` +
    Object.entries(posts.reduce((a, p) => ((a[p.channel] = (a[p.channel] || 0) + 1), a), {}))
      .map(([k, v]) => `${k} ×${v}`).join(' · ') + `_\n`;

  for (const key of Object.keys(LABEL)) {
    const mine = posts.filter((p) => p.channel === key);
    if (!mine.length) continue;
    const blocked = mine.some((p) => p.blockedOnLinkedInPageApproval);
    md += `\n## ${LABEL[key]}${blocked ? ' ⛔ BLOCKED' : ''}\n`;
    for (const p of mine) {
      md += `\n### ${slot(p.date)}${p.needsConfirmation ? ' 🔶' : ''}\n`;
      const meta = [p.territory, p.skeleton].filter(Boolean).map((x) => `\`${x}\``).join(' · ') || '`unclassified`';
      md += `${meta}${p.needsConfirmation ? ' · **needs confirmation**' : ''}${p.blockedOnLinkedInPageApproval ? ' · **blocked: LinkedIn Page API**' : ''}\n\n`;
      md += '```\n' + p.content + '\n```\n';
    }
  }
}
writeFileSync(out, md);
console.log(`wrote ${out}`);
